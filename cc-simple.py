#!/usr/bin/env python3
"""
cc-simple.py - Simple Codex configuration switcher
Manages provider configurations for Codex from YAML files
"""

import os
import sys
import argparse
from pathlib import Path
import shutil


class ConfigManager:
    def __init__(self):
        self.home = Path.home()
        self.codex_config_dir = self.home / ".codex"
        self.codex_config_file = self.codex_config_dir / "config.toml"
        self.project_dir = Path(__file__).parent
        self.confs_dir = self.project_dir / "confs"

        # Ensure directories exist
        self.confs_dir.mkdir(exist_ok=True)

    def parse_yaml_config(self, yaml_file):
        """Parse simple key=value YAML format"""
        config = {}
        with open(yaml_file, 'r') as f:
            for line in f:
                line = line.strip()
                if line and '=' in line:
                    key, value = line.split('=', 1)
                    config[key.strip()] = value.strip()
        return config

    def add_config(self, yaml_file):
        """Add a configuration from YAML file"""
        yaml_path = Path(yaml_file)
        if not yaml_path.exists():
            print(f"Error: {yaml_file} not found")
            return False

        config = self.parse_yaml_config(yaml_path)

        # Validate required fields
        required = ['name', 'base_url', 'type']
        for field in required:
            if field not in config:
                print(f"Error: missing required field '{field}'")
                return False

        # Copy to confs directory with index
        existing_confs = list(self.confs_dir.glob("*.yaml"))
        index = len(existing_confs) + 1
        dest_file = self.confs_dir / f"{index}_{config['name']}.yaml"

        shutil.copy(yaml_path, dest_file)
        print(f"Added configuration: {config['name']} (ID: {index})")
        return True

    def list_configs(self):
        """List all stored configurations"""
        confs = sorted(self.confs_dir.glob("*.yaml"))

        if not confs:
            print("No configurations found")
            return

        for conf_file in confs:
            # Extract index from filename (format: 1_name.yaml)
            parts = conf_file.stem.split('_', 1)
            if len(parts) == 2 and parts[0].isdigit():
                index, name = parts
                config = self.parse_yaml_config(conf_file)
                base_url = config.get('base_url', 'N/A')
                print(f"{index} {name} {base_url}")
            # Skip files without proper ID_name format

    def generate_toml_content(self, config):
        """Generate TOML content for the provider"""
        provider_type = config.get('type', 'openai')

        if provider_type == 'openai':
            return self._generate_openai_toml(config)
        elif provider_type == 'anthropic':
            return self._generate_anthropic_toml(config)
        else:
            print(f"Warning: unknown type '{provider_type}', using OpenAI format")
            return self._generate_openai_toml(config)

    def _generate_openai_toml(self, config):
        """Generate OpenAI provider TOML"""
        provider_name = config.get('name', 'unnamed')
        api_key = config.get('api_key', config.get('model', 'sk-xxx'))
        base_url = config.get('base_url', '')
        model = config.get('model_name', 'gpt-4')

        toml = f"""# Generated by cc-simple.py
# Provider: {provider_name}

model_provider = "{provider_name}"
model = "{model}"

[model_providers.{provider_name}]
name = "{provider_name}"
base_url = "{base_url}"
wire_api = "chat"

[model_providers.{provider_name}.auth]
header = "Authorization"
value = "Bearer {api_key}"

[tui]
screen_reader_detection_done = true
"""
        return toml

    def _generate_anthropic_toml(self, config):
        """Generate Anthropic provider TOML"""
        provider_name = config.get('name', 'unnamed')
        api_key = config.get('api_key', config.get('model', 'sk-ant-xxx'))
        base_url = config.get('base_url', 'https://api.anthropic.com')
        model = config.get('model_name', 'claude-opus-5-5')

        toml = f"""# Generated by cc-simple.py
# Provider: {provider_name}

model_provider = "{provider_name}"
model = "{model}"

[model_providers.{provider_name}]
name = "{provider_name}"
base_url = "{base_url}"
wire_api = "responses"

[model_providers.{provider_name}.auth]
header = "x-api-key"
value = "{api_key}"

[tui]
screen_reader_detection_done = true
"""
        return toml

    def use_config(self, config_id):
        """Switch to a specific configuration"""
        # Find config file by ID
        target_file = None
        for conf_file in self.confs_dir.glob("*.yaml"):
            parts = conf_file.stem.split('_', 1)
            if len(parts) == 2 and parts[0] == str(config_id):
                target_file = conf_file
                break

        if not target_file:
            print(f"Error: configuration ID {config_id} not found")
            return False

        # Parse config
        config = self.parse_yaml_config(target_file)

        # Generate TOML content
        toml_content = self.generate_toml_content(config)

        # Backup existing config if it exists
        if self.codex_config_file.exists():
            backup_file = self.codex_config_file.with_suffix('.toml.bak')
            shutil.copy(self.codex_config_file, backup_file)
            print(f"Backed up existing config to {backup_file}")

        # Ensure codex config directory exists
        self.codex_config_dir.mkdir(parents=True, exist_ok=True)

        # Write new config
        with open(self.codex_config_file, 'w') as f:
            f.write(toml_content)

        print(f"Switched to configuration: {config.get('name', 'unnamed')} (ID: {config_id})")
        print(f"Provider type: {config.get('type', 'openai')}")
        print(f"Base URL: {config.get('base_url', 'N/A')}")
        return True


def main():
    parser = argparse.ArgumentParser(
        description='Simple Codex configuration switcher',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Add a configuration
  cc-simple.py add conf.yaml

  # List all configurations
  cc-simple.py list

  # Switch to configuration ID 1
  cc-simple.py use 1
        """
    )

    subparsers = parser.add_subparsers(dest='command', help='Command to execute')

    # Add command
    add_parser = subparsers.add_parser('add', help='Add a configuration from YAML file')
    add_parser.add_argument('yaml_file', help='Path to YAML configuration file')

    # List command
    subparsers.add_parser('list', help='List all configurations')

    # Use command
    use_parser = subparsers.add_parser('use', help='Switch to a configuration')
    use_parser.add_argument('config_id', type=int, help='Configuration ID to use')

    args = parser.parse_args()

    if not args.command:
        parser.print_help()
        return 1

    manager = ConfigManager()

    if args.command == 'add':
        success = manager.add_config(args.yaml_file)
        return 0 if success else 1

    elif args.command == 'list':
        manager.list_configs()
        return 0

    elif args.command == 'use':
        success = manager.use_config(args.config_id)
        return 0 if success else 1

    return 0


if __name__ == '__main__':
    sys.exit(main())
